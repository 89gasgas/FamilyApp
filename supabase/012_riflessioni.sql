-- RI-07: settings keys ri_new, ri_heart, ri_daily (missing = on)
create or replace function public.set_notify(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r jsonb; k text;
begin
  if (p ? 'shop' and p->>'shop' not in ('none','urgent','all'))
     or (p ? 'todo' and p->>'todo' not in ('none','mine','all')) then
    raise exception 'bad value';
  end if;
  foreach k in array array['morning', 'cal', 'ri_new', 'ri_heart', 'ri_daily'] loop
    if p ? k and jsonb_typeof(p->k) <> 'boolean' then raise exception 'bad value'; end if;
  end loop;
  update public.members set notify = notify || jsonb_strip_nulls(jsonb_build_object(
    'shop', p->'shop', 'todo', p->'todo', 'morning', p->'morning', 'cal', p->'cal',
    'ri_new', p->'ri_new', 'ri_heart', p->'ri_heart', 'ri_daily', p->'ri_daily'))
  where email = private.me() returning notify into r;
  return r;
end $$;

-- short preview of a reflection for a notification: start of the text and the author
create or replace function private.ri_preview(r public.reflections) returns text language sql stable as $$
  select case when length(t) > 140 then left(t, 137) || '…' else t end
         || coalesce(' — ' || nullif(trim(r.author), ''), '')
  from (select regexp_replace(trim(r.body), '\s+', ' ', 'g') t) x
$$;

-- RI-07: a new reflection from the other one
create or replace function private.on_reflection() returns trigger
language plpgsql security definer set search_path = public as $$
declare who text; items jsonb;
begin
  select display_name into who from public.members where email = new.created_by;
  select coalesce(jsonb_agg(jsonb_build_object('email', m.email, 'payload', jsonb_build_object(
           'title', '💭 ' || coalesce(who, 'Nuova riflessione'), 'body', private.ri_preview(new),
           'tag', 'ref-' || new.id, 'url', './?tab=ref&ref=' || new.id))), '[]')
    into items
  from public.members m
  where m.family_id = new.family_id and m.email <> new.created_by
    and coalesce((m.notify->>'ri_new')::boolean, true);
  perform private.push_enqueue(items);
  return null;
end $$;
drop trigger if exists reflection_notify on public.reflections;
create trigger reflection_notify after insert on public.reflections
  for each row execute function private.on_reflection();

-- RI-07: a heart on my reflection
create or replace function private.on_heart() returns trigger
language plpgsql security definer set search_path = public as $$
declare r public.reflections; who text;
begin
  select * into r from public.reflections where id = new.reflection_id;
  if r.id is null or r.created_by = new.email then return null; end if;
  if not exists (select 1 from public.members where email = r.created_by
                 and coalesce((notify->>'ri_heart')::boolean, true)) then return null; end if;
  select display_name into who from public.members where email = new.email;
  perform private.push_enqueue(jsonb_build_array(jsonb_build_object('email', r.created_by, 'payload',
    jsonb_build_object('title', '❤️ ' || coalesce(who, '') || ' ha messo un cuore', 'body', private.ri_preview(r),
                       'tag', 'heart-' || r.id, 'url', './?tab=ref&ref=' || r.id))));
  return null;
end $$;
drop trigger if exists heart_notify on public.reflection_hearts;
create trigger heart_notify after insert on public.reflection_hearts
  for each row execute function private.on_heart();

-- RI-07: at 8:00 every family gets one reflection of the day, the same for everyone.
-- Never-picked ones first, then the ones picked longest ago: no repeats until all have come out.
-- p_force runs it now (tests); it never picks twice on the same day.
create or replace function private.push_reflection_daily(p_force boolean default false) returns int
language plpgsql security definer set search_path = public as $$
declare f record; r public.reflections; today date := (now() at time zone 'Europe/Rome')::date;
        items jsonb := '[]'; n int := 0;
begin
  if not p_force and extract(hour from now() at time zone 'Europe/Rome') <> 8 then return 0; end if;
  for f in select distinct family_id from public.reflections
           where family_id not in (select family_id from public.reflections where daily_on = today) loop
    select * into r from public.reflections where family_id = f.family_id
    order by daily_on nulls first, random() limit 1;
    update public.reflections set daily_on = today where id = r.id;
    select coalesce(jsonb_agg(jsonb_build_object('email', m.email, 'payload', jsonb_build_object(
             'title', '💭 La riflessione di oggi', 'body', private.ri_preview(r),
             'tag', 'ref-daily', 'url', './?tab=ref&ref=' || r.id))), '[]')
      into items
    from public.members m
    where m.family_id = f.family_id and coalesce((m.notify->>'ri_daily')::boolean, true);
    perform private.push_enqueue(items);
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function private.push_reflection_daily(boolean) from public, anon, authenticated;
select cron.schedule('fa-reflection', '0 * * * *', 'select private.push_reflection_daily()');

-- RI-08: daily backup now includes reflections and hearts.
create or replace function public.backup_export(p_key text) returns json
language plpgsql security definer set search_path = public as $$
begin
  if p_key is null or encode(sha256(convert_to(p_key, 'UTF8')), 'hex')
       is distinct from (select value from private.config where key = 'backup_key_sha256') then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  return json_build_object(
    'families', (select coalesce(json_agg(f order by f.id), '[]') from public.families f),
    'members', (select coalesce(json_agg(m order by m.email), '[]') from public.members m),
    'shopping_items', (select coalesce(json_agg(i order by i.family_id, i.position, i.id), '[]')
                       from public.shopping_items i),
    'tasks', (select coalesce(json_agg(t order by t.family_id, t.created_at, t.id), '[]') from public.tasks t),
    'expense_categories', (select coalesce(json_agg(c order by c.family_id, c.position, c.id), '[]')
                           from public.expense_categories c),
    'expenses', (select coalesce(json_agg(e order by e.family_id, e.spent_on, e.created_at, e.id), '[]')
                 from public.expenses e),
    'events', (select coalesce(json_agg(v order by v.family_id, v.day, v.created_at, v.id), '[]')
               from public.events v),
    'reflections', (select coalesce(json_agg(r order by r.family_id, r.created_at, r.id), '[]')
                    from public.reflections r),
    'reflection_hearts', (select coalesce(json_agg(h order by h.family_id, h.created_at, h.id), '[]')
                          from public.reflection_hearts h));
end $$;
revoke execute on function public.backup_export(text) from public, anon, authenticated;
grant execute on function public.backup_export(text) to anon;

select 'ok' as result;
