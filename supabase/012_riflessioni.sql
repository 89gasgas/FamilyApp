-- FamilyApp: increment 6, reflections (RI-01…RI-08). Idempotent.

create table if not exists public.reflections (
  id uuid primary key default gen_random_uuid(),               -- generated by the client (offline replay)
  family_id uuid not null references public.families(id) on delete cascade,
  body text not null check (length(trim(body)) > 0),            -- RI-01: the thought or quote, may be long
  author text,                                                  -- empty = my own thought
  source text,                                                  -- book, film, podcast…
  tags text[] not null default '{}',                            -- RI-02: free tags, stored lower-case
  created_by text not null,                                     -- member email: only they edit or delete it
  daily_on date,                                                -- RI-07: last day it was "la riflessione del giorno"
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists reflections_family on public.reflections (family_id, created_at);

-- RI-05: one heart per person per reflection
create table if not exists public.reflection_hearts (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families(id) on delete cascade,
  reflection_id uuid not null references public.reflections(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now(),
  unique (reflection_id, email)
);

alter table public.reflections enable row level security;
alter table public.reflection_hearts enable row level security;
-- RI-03: everyone in the family reads everything; RI-06: only the author writes
drop policy if exists reflections_read on public.reflections;
create policy reflections_read on public.reflections for select to authenticated
  using (family_id = public.my_family());
drop policy if exists reflections_add on public.reflections;
create policy reflections_add on public.reflections for insert to authenticated
  with check (family_id = public.my_family() and created_by = private.me());
drop policy if exists reflections_edit on public.reflections;
create policy reflections_edit on public.reflections for update to authenticated
  using (family_id = public.my_family() and created_by = private.me())
  with check (family_id = public.my_family() and created_by = private.me());
drop policy if exists reflections_del on public.reflections;
create policy reflections_del on public.reflections for delete to authenticated
  using (family_id = public.my_family() and created_by = private.me());
-- RI-05: a heart is mine, on someone else's reflection
drop policy if exists hearts_read on public.reflection_hearts;
create policy hearts_read on public.reflection_hearts for select to authenticated
  using (family_id = public.my_family());
drop policy if exists hearts_add on public.reflection_hearts;
create policy hearts_add on public.reflection_hearts for insert to authenticated
  with check (family_id = public.my_family() and email = private.me() and exists (
    select 1 from public.reflections r where r.id = reflection_id and r.family_id = public.my_family()
      and r.created_by <> private.me()));
drop policy if exists hearts_del on public.reflection_hearts;
create policy hearts_del on public.reflection_hearts for delete to authenticated
  using (family_id = public.my_family() and email = private.me());

drop trigger if exists reflections_touch on public.reflections;
