-- FamilyApp: increment 4, monthly expenses (CO-01…CO-08). Outgoings only. Idempotent.

create table if not exists public.expense_categories (
  id uuid primary key default gen_random_uuid(),               -- generated by the client (offline replay)
  family_id uuid not null references public.families(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  icon text not null default '💶',
  color text not null default '#2f7d5b' check (color ~ '^#[0-9a-fA-F]{6}$'),
  position double precision not null default 0,
  hidden boolean not null default false,                        -- CO-07: hide instead of delete
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists expense_categories_family on public.expense_categories (family_id);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families(id) on delete cascade,
  category_id uuid not null references public.expense_categories(id) on delete restrict,
  amount_cents integer not null check (amount_cents > 0),
  note text,
  spent_on date not null default ((now() at time zone 'Europe/Rome')::date),
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists expenses_family_day on public.expenses (family_id, spent_on);

do $$ declare t text; begin
  foreach t in array array['expense_categories', 'expenses'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_all', t);
    execute format('create policy %I on public.%I for all to authenticated
                    using (family_id = public.my_family()) with check (family_id = public.my_family())', t || '_all', t);
    execute format('drop trigger if exists %I on public.%I', t || '_touch', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.touch_updated_at()',
                   t || '_touch', t);
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
    execute format('alter table public.%I replica identity full', t);
  end loop;
end $$;

-- A category's expenses must belong to the same family.
create or replace function private.check_expense_family() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.expense_categories c where c.id = new.category_id and c.family_id = new.family_id) then
    raise exception 'category of another family';
  end if;
  return new;
end $$;
drop trigger if exists expenses_family on public.expenses;
create trigger expenses_family before insert or update of category_id, family_id on public.expenses
  for each row execute function private.check_expense_family();

