-- FamilyApp: increment 5, family calendar with repeats and reminders (CA-01…CA-09). Idempotent.

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),               -- generated by the client (offline replay)
  family_id uuid not null references public.families(id) on delete cascade,
  title text not null check (length(trim(title)) > 0),
  day date not null,                                            -- first (or only) day
  until date check (until is null or until >= day),             -- CA-04: several days (holidays)
  who text not null default 'both',                             -- member email or 'both', as in to-dos
  repeat text not null default 'none' check (repeat in ('none', 'week', 'month', 'year')),
  remind text not null default 'none' check (remind in ('none', 'morning', 'evening')),
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists events_family_day on public.events (family_id, day);

alter table public.events enable row level security;
drop policy if exists events_all on public.events;
create policy events_all on public.events for all to authenticated
  using (family_id = public.my_family()) with check (family_id = public.my_family());
drop trigger if exists events_touch on public.events;
create trigger events_touch before update on public.events for each row execute function public.touch_updated_at();
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'events') then
    alter publication supabase_realtime add table public.events;
  end if;
end $$;
alter table public.events replica identity full;

-- CA-06: does an occurrence of the event START on p_on? (end of month and 29 February fall on the last day)
create or replace function private.starts_on(p_day date, p_repeat text, p_on date) returns boolean
language sql immutable as $$
  select p_on >= p_day and case p_repeat
    when 'none' then p_on = p_day
    when 'week' then (p_on - p_day) % 7 = 0
    when 'month' then extract(day from p_on) = least(extract(day from p_day),
      extract(day from (date_trunc('month', p_on) + interval '1 month - 1 day')))
    when 'year' then extract(month from p_on) = extract(month from p_day) and extract(day from p_on) = least(
      extract(day from p_day), extract(day from (date_trunc('month', p_on) + interval '1 month - 1 day')))
    else false end
$$;

-- CA-07: settings key "cal" (calendar reminders on this person's phones; missing = on)
create or replace function public.set_notify(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r jsonb;
begin
  if (p ? 'shop' and p->>'shop' not in ('none','urgent','all'))
     or (p ? 'todo' and p->>'todo' not in ('none','mine','all'))
     or (p ? 'morning' and jsonb_typeof(p->'morning') <> 'boolean')
     or (p ? 'cal' and jsonb_typeof(p->'cal') <> 'boolean') then
    raise exception 'bad value';
  end if;
  update public.members set notify = notify || jsonb_strip_nulls(jsonb_build_object(
    'shop', p->'shop', 'todo', p->'todo', 'morning', p->'morning', 'cal', p->'cal'))
  where email = private.me() returning notify into r;
  return r;
end $$;

-- CA-07: at 8:00 the reminders "la mattina stessa" (today), at 20:00 "la sera prima" (tomorrow).
-- p_hour forces a run as if it were that hour (tests).
create or replace function private.push_calendar(p_hour int default null) returns int
language plpgsql security definer set search_path = public as $$
declare
  h int := coalesce(p_hour, extract(hour from now() at time zone 'Europe/Rome')::int);
  target date := (now() at time zone 'Europe/Rome')::date + case when h = 20 then 1 else 0 end;
  kind text := case h when 8 then 'morning' when 20 then 'evening' end;
  r record; items jsonb := '[]';
begin
  if kind is null then return 0; end if;
  for r in
    select m.email, string_agg(e.title, ', ' order by e.created_at) titles
    from public.members m join public.events e on e.family_id = m.family_id
    where coalesce((m.notify->>'cal')::boolean, true) and e.remind = kind
      and e.who in (m.email, 'both') and private.starts_on(e.day, e.repeat, target)
    group by m.email
  loop
    items := items || jsonb_build_object('email', r.email, 'payload', jsonb_build_object(
      'title', case kind when 'morning' then '📅 Oggi' else '📅 Domani' end,
      'body', r.titles, 'tag', 'cal-' || target,
      'url', './?tab=cal&day=' || target));
  end loop;
  perform private.push_enqueue(items);
  return jsonb_array_length(items);
end $$;
revoke execute on function private.push_calendar(int) from public, anon, authenticated;

select cron.schedule('fa-calendar', '0 * * * *', 'select private.push_calendar()');

-- CA-09: daily backup now includes events.
create or replace function public.backup_export(p_key text) returns json
language plpgsql security definer set search_path = public as $$
begin
  if p_key is null or encode(sha256(convert_to(p_key, 'UTF8')), 'hex')
       is distinct from (select value from private.config where key = 'backup_key_sha256') then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  return json_build_object(
    'families', (select coalesce(json_agg(f order by f.id), '[]') from public.families f),
    'members', (select coalesce(json_agg(m order by m.email), '[]') from public.members m),
    'shopping_items', (select coalesce(json_agg(i order by i.family_id, i.position, i.id), '[]')
                       from public.shopping_items i),
    'tasks', (select coalesce(json_agg(t order by t.family_id, t.created_at, t.id), '[]') from public.tasks t),
    'expense_categories', (select coalesce(json_agg(c order by c.family_id, c.position, c.id), '[]')
                           from public.expense_categories c),
    'expenses', (select coalesce(json_agg(e order by e.family_id, e.spent_on, e.created_at, e.id), '[]')
                 from public.expenses e),
    'events', (select coalesce(json_agg(v order by v.family_id, v.day, v.created_at, v.id), '[]')
               from public.events v));
end $$;
revoke execute on function public.backup_export(text) from public, anon, authenticated;
grant execute on function public.backup_export(text) to anon;

