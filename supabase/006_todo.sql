-- FamilyApp: increment 2, shared to-dos (TD-01…TD-07). Idempotent.

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),            -- generated by the client (offline replay)
  family_id uuid not null references public.families(id) on delete cascade,
  title text not null check (length(trim(title)) > 0),
  assignee text check (assignee is null or assignee = 'both' or assignee = lower(assignee)), -- member email | 'both' | null
  due date,
  done boolean not null default false,
  done_by text,
  done_at timestamptz,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists tasks_family on public.tasks (family_id);

alter table public.tasks enable row level security;
drop policy if exists tasks_all on public.tasks;
create policy tasks_all on public.tasks for all to authenticated
  using (family_id = public.my_family())
  with check (family_id = public.my_family());

drop trigger if exists tasks_touch on public.tasks;
create trigger tasks_touch before update on public.tasks
  for each row execute function public.touch_updated_at();

-- Realtime (TD-03); full identity so deletes reach the other phone with their family_id.
do $$ begin
  if not exists (select 1 from pg_publication_tables
                 where pubname = 'supabase_realtime' and tablename = 'tasks') then
    alter publication supabase_realtime add table public.tasks;
  end if;
end $$;
alter table public.tasks replica identity full;

-- Daily backup now includes the tasks.
create or replace function public.backup_export(p_key text) returns json
language plpgsql security definer set search_path = public as $$
begin
  if p_key is null or encode(sha256(convert_to(p_key, 'UTF8')), 'hex')
       is distinct from (select value from private.config where key = 'backup_key_sha256') then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  return json_build_object(
    'families', (select coalesce(json_agg(f order by f.id), '[]') from public.families f),
    'members', (select coalesce(json_agg(m order by m.email), '[]') from public.members m),
    'shopping_items', (select coalesce(json_agg(i order by i.family_id, i.position, i.id), '[]')
                       from public.shopping_items i),
    'tasks', (select coalesce(json_agg(t order by t.family_id, t.created_at, t.id), '[]') from public.tasks t));
end $$;
revoke execute on function public.backup_export(text) from public, anon, authenticated;
grant execute on function public.backup_export(text) to anon;

select 'ok' as result;
